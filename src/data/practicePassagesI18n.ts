/**
 * Returns localized practice levels for the given language.
 * Falls back to default English levels for any missing levels.
 */
export function getLocalizedPracticeLevels(lang: SupportedLocale = 'en'): PracticeLevel[] {
  if (lang === 'en') {
    return PRACTICE_LEVELS;
  }

  const localizedList = LOCALIZED_PRACTICE_LEVELS[lang];
  if (!localizedList || localizedList.length === 0) {
    return PRACTICE_LEVELS;
  }

  // Merge localized levels over base PRACTICE_LEVELS
  return PRACTICE_LEVELS.map((baseLevel) => {
    const override = localizedList.find((l) => l.level === baseLevel.level);
    if (!override) {
      return baseLevel;
    }
    return {
      ...baseLevel,
      name: override.name || baseLevel.name,
      tagline: override.tagline || baseLevel.tagline,
      description: override.description || baseLevel.description,
      badge: override.badge || baseLevel.badge,
      passages: override.passages && override.passages.length > 0 ? override.passages : baseLevel.passages,
    };
  });
}
